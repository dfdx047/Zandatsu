#!/usr/bin/env python3
"""livediff_wraps: link-time wrappers for pc/runtime/linux/livediff.cpp (Linux lab host only).

    livediff_wraps.py <outdir> <VA|sub_X|@file> ...

Writes <outdir>/wraps.c (one __wrap_sub_X per function, calling livediff_call) and <outdir>/wrap.rsp (the linker's
--wrap list). Configure the host with -DMGR_LIVEDIFF_DIR=<outdir>; only the link and wraps.c are redone when the
list changes. Functions not in the gen (aliases, excluded) are dropped with a note.
"""
import os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))


def main():
    out = sys.argv[1]
    vas = []
    for a in sys.argv[2:]:
        items = open(a[1:]).read().split() if a.startswith('@') else [a]
        for it in items:
            it = it.split('#')[0].strip()
            if it:
                vas.append(int(it[4:] if it.startswith('sub_') else it, 16))
    decl = open(os.path.join(ROOT, 'build', 'pc', 'gen', 'recomp_funcs.h')).read()
    have = set(int(m, 16) for m in re.findall(r'void sub_([0-9A-F]{8})\(void\);', decl))
    vas = sorted(set(v for v in vas if v in have or print(f'not in gen: {v:08X}')))
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, 'wraps.c'), 'w') as f:
        f.write('/* generated by pc/tools/livediff_wraps.py */\n#include <stdint.h>\n'
                'void livediff_call(uint32_t va, void (*real)(void));\n')
        for v in vas:
            f.write(f'void __real_sub_{v:08X}(void);\nvoid __wrap_sub_{v:08X}(void) '
                    f'{{ livediff_call(0x{v:08X}u, __real_sub_{v:08X}); }}\n')
    with open(os.path.join(out, 'wrap.rsp'), 'w') as f:
        f.write(''.join(f'--wrap=sub_{v:08X}\n' for v in vas))
    print(f'{len(vas)} wrappers in {out}')


if __name__ == '__main__':
    main()
